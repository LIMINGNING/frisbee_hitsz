def replace_team(tex, team_name, members):
    pattern = r'(\\noindent \\textbf\{' + team_name + r'运动员名单及签名：\}.*?\\midrule)(.*?)(^[ \t]*\\bottomrule)'
    
    rows = []
    for m in members:
        row = f"    {m[0]} & {m[1]} & {m[2]} & {m[3]} & \\rule{{3cm}}{{0.4pt}} \\\\"
        rows.append(row)
    
    replacement = r'\1\n' + '\n'.join(rows) + r'\n\3'
    return re.sub(pattern, replacement, tex, flags=re.DOTALL | re.MULTILINE)

for team, members in teams.items():
    tex = replace_team(tex, team, members)

